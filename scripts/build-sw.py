#!/usr/bin/env python3
"""Write the hub's sw.js.

The hub precaches only itself -- the page, its two scripts, its
stylesheet and its icons, a handful of files. It deliberately does NOT
precache any course. Each course has its own service worker and its own
generated precache list, and keeping that the one source of truth is
what lets a course be added, rebuilt or deployed without a change here.

What this worker does have to get right is staying out of the courses'
way. Its scope is "/", the whole origin, which also covers every course
folder -- so until a student has opened a course once, requests for that
course arrive here, at the hub's worker, rather than at the course's
own. Those requests are passed straight to the network and never
cached, for two reasons:

  * caching them here would store a second, stale copy of pages the
    course's own worker already owns; and
  * answering them from the hub's shell when offline would render the
    hub's HTML under the course's URL, where every relative link
    resolves one directory too deep.

So a course that has not been saved simply fails to open offline, which
is the truth, and the hub's home page says as much.

Run it whenever a hub file is added or removed:

    python3 scripts/build-sw.py
    python3 scripts/build-sw.py --check
"""
import datetime
import io
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PREFIX = "hub-"

DIRS = ["assets", "icons"]
FILES = ["index.html", "manifest.webmanifest"]

SKIP_SUFFIX = (".py", ".md", ".map")
SKIP_NAMES = {".DS_Store", "Thumbs.db"}

TEMPLATE = u'''/* ============================================================
   Service worker -- generated by scripts/build-sw.py, do not edit.

   The hub's own shell, and nothing else. Every course keeps its own
   worker, its own precache list and its own cache; this one must not
   duplicate or shadow any of them.

   Scope is "/", so this worker also sits in front of every course
   folder until that course has been opened once and registered its
   own, more specific worker. Course requests are therefore passed to
   the network untouched -- never cached here, and never answered from
   the hub's shell, which under a course URL would resolve all of its
   relative links one directory too deep.

   CACHE changes on every build, and the activate handler deletes only
   caches starting with "hub-". The six courses' caches live on this
   same origin and are visible from here; deleting them would take
   those courses offline.
   ============================================================ */
'use strict';

var CACHE = '%(cache)s';
var PREFIX = '%(prefix)s';

/* Kept in step with the course list in assets/js/hub.js by the build
   script that wrote this file. */
var COURSES = [
%(courses)s
];

var PRECACHE = [
  "./",
%(assets)s
];

function isCourse(url) {
  /* url.pathname is absolute ("/linear-algebra/..."); the hub is served
     from the origin root, so a leading-slash compare is enough. */
  for (var i = 0; i < COURSES.length; i++) {
    if (url.pathname.indexOf('/' + COURSES[i] + '/') === 0) return true;
  }
  return false;
}

self.addEventListener('install', function (event) {
  event.waitUntil(
    caches.open(CACHE).then(function (cache) {
      /* Added one at a time: addAll rejects as a unit, so a single 404
         would leave the worker uninstalled and the hub with no offline
         support at all. */
      return Promise.all(PRECACHE.map(function (url) {
        return cache.add(new Request(url, { cache: 'reload' }))['catch'](function () {});
      }));
    }).then(function () { return self.skipWaiting(); })
  );
});

self.addEventListener('activate', function (event) {
  event.waitUntil(
    caches.keys().then(function (keys) {
      return Promise.all(keys.map(function (k) {
        if (k === CACHE) return null;
        return k.indexOf(PREFIX) === 0 ? caches['delete'](k) : null;
      }));
    }).then(function () { return self.clients.claim(); })
  );
});

self.addEventListener('message', function (event) {
  if (event.data === 'skipWaiting') self.skipWaiting();
});

self.addEventListener('fetch', function (event) {
  var req = event.request;
  if (req.method !== 'GET') return;

  var url = new URL(req.url);
  if (url.origin !== self.location.origin) return;

  /* A course's own worker owns these once it exists. Until then, the
     network answers or nothing does. */
  if (isCourse(url)) return;

  if (req.mode === 'navigate') {
    event.respondWith(
      fetch(req).then(function (res) {
        if (res && res.ok) {
          var copy = res.clone();
          caches.open(CACHE).then(function (c) { c.put(req, copy); });
        }
        return res;
      })['catch'](function () {
        return caches.match(req).then(function (hit) {
          return hit || caches.match('./');
        });
      })
    );
    return;
  }

  event.respondWith(
    caches.match(req).then(function (hit) {
      if (hit) return hit;
      return fetch(req).then(function (res) {
        if (res && res.status === 200 && res.type === 'basic') {
          var copy = res.clone();
          caches.open(CACHE).then(function (c) { c.put(req, copy); });
        }
        return res;
      });
    })
  );
});
'''


def course_slugs():
    """The course folders, read from hub.js so the two cannot drift.

    hub.js is the hand-edited list; duplicating it here by hand is
    exactly the kind of copy that goes stale the first time a course is
    added and nobody remembers there were two places.
    """
    path = os.path.join(ROOT, "assets", "js", "hub.js")
    text = io.open(path, encoding="utf-8").read()
    slugs = re.findall(r'^\s*slug:\s*"([^"]+)"', text, re.M)
    return sorted(set(slugs))


def walk():
    """Every hub file, as a site-root-relative path, sorted."""
    out = []
    for name in FILES:
        if os.path.exists(os.path.join(ROOT, name)):
            out.append(name)
    for d in DIRS:
        base = os.path.join(ROOT, d)
        if not os.path.isdir(base):
            continue
        for dirpath, dirnames, filenames in os.walk(base):
            dirnames[:] = [x for x in dirnames
                           if not x.startswith(".") and x != "__pycache__"]
            for f in sorted(filenames):
                if (f in SKIP_NAMES or f.endswith(SKIP_SUFFIX)
                        or f.endswith(".pyc") or f.startswith(".")):
                    continue
                full = os.path.join(dirpath, f)
                out.append(os.path.relpath(full, ROOT).replace(os.sep, "/"))
    return sorted(set(out))


def next_cache_name(today):
    """A fresh name every build: same day twice means bump the counter."""
    path = os.path.join(ROOT, "sw.js")
    n = 1
    if os.path.exists(path):
        current = io.open(path, encoding="utf-8").read()
        m = re.search(r"var CACHE = '" + PREFIX + r"(\d{8})-(\d+)'", current)
        if m and m.group(1) == today:
            n = int(m.group(2)) + 1
    return "%s%s-%d" % (PREFIX, today, n)


def main():
    check = "--check" in sys.argv
    files = walk()
    slugs = course_slugs()
    path = os.path.join(ROOT, "sw.js")

    if not files:
        print("nothing to precache", file=sys.stderr)
        return 1
    if not slugs:
        print("no course slugs found in assets/js/hub.js", file=sys.stderr)
        return 1

    if check:
        current = io.open(path, encoding="utf-8").read() if os.path.exists(path) else ""
        listed = [x for x in re.findall(r'^  "([^"]+)",?$', current, re.M) if x != "./"]
        missing = sorted(set(files) - set(listed))
        gone = sorted(set(listed) - set(files))
        listed_slugs = sorted(set(re.findall(r"^  '([^']+)',?$", current, re.M)))
        bad = 0
        if missing:
            print("sw.js does not precache: %s" % ", ".join(missing), file=sys.stderr)
            bad = 1
        if gone:
            print("sw.js precaches files that no longer exist: %s"
                  % ", ".join(gone), file=sys.stderr)
            bad = 1
        if listed_slugs != slugs:
            print("sw.js course list is out of step with hub.js: %s vs %s"
                  % (listed_slugs, slugs), file=sys.stderr)
            bad = 1
        if bad:
            return 1
        print("sw.js precaches all %d hub files and knows %d courses"
              % (len(files), len(slugs)))
        return 0

    today = datetime.date.today().strftime("%Y%m%d")
    assets = "\n".join('  "%s"%s' % (f, "," if i < len(files) - 1 else "")
                       for i, f in enumerate(files))
    courses = "\n".join("  '%s'%s" % (s, "," if i < len(slugs) - 1 else "")
                        for i, s in enumerate(slugs))

    text = TEMPLATE % {
        "cache": next_cache_name(today),
        "prefix": PREFIX,
        "assets": assets,
        "courses": courses,
    }
    io.open(path, "w", encoding="utf-8", newline="\n").write(text)
    print("wrote sw.js -- %d files precached, %d courses passed through"
          % (len(files) + 1, len(slugs)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
