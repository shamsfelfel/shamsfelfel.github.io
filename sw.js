/* ============================================================
   Service worker -- generated by scripts/build-sw.py, do not edit.

   The hub's own shell, and nothing else. Every course keeps its own
   worker, its own precache list and its own cache; this one must not
   duplicate or shadow any of them.

   Scope is "/", so this worker also sits in front of every course
   folder until that course has been opened once and registered its
   own, more specific worker. Course requests are therefore passed to
   the network untouched -- never cached here, and never answered from
   the hub's shell, which under a course URL would resolve all of its
   relative links one directory too deep.

   CACHE changes on every build, and the activate handler deletes only
   caches starting with "hub-". The six courses' caches live on this
   same origin and are visible from here; deleting them would take
   those courses offline.
   ============================================================ */
'use strict';

var CACHE = 'hub-20261104-1';
var PREFIX = 'hub-';

/* Kept in step with the course list in assets/js/hub.js by the build
   script that wrote this file. */
var COURSES = [
  'ESL',
  'data-analysis-and-implementation',
  'database-sql',
  'discrete-math',
  'linear-algebra',
  'programming-ai'
];

var PRECACHE = [
  "./",
  "assets/css/hub.css",
  "assets/js/hub.js",
  "assets/js/i18n.js",
  "assets/js/theme.js",
  "icons/apple-touch-icon.png",
  "icons/icon-192.png",
  "icons/icon-512.png",
  "icons/icon-maskable-512.png",
  "index.html",
  "manifest.webmanifest"
];

function isCourse(url) {
  /* url.pathname is absolute ("/linear-algebra/..."); the hub is served
     from the origin root, so a leading-slash compare is enough. */
  for (var i = 0; i < COURSES.length; i++) {
    if (url.pathname.indexOf('/' + COURSES[i] + '/') === 0) return true;
  }
  return false;
}

self.addEventListener('install', function (event) {
  event.waitUntil(
    caches.open(CACHE).then(function (cache) {
      /* Added one at a time: addAll rejects as a unit, so a single 404
         would leave the worker uninstalled and the hub with no offline
         support at all. */
      return Promise.all(PRECACHE.map(function (url) {
        return cache.add(new Request(url, { cache: 'reload' }))['catch'](function () {});
      }));
    }).then(function () { return self.skipWaiting(); })
  );
});

self.addEventListener('activate', function (event) {
  event.waitUntil(
    caches.keys().then(function (keys) {
      return Promise.all(keys.map(function (k) {
        if (k === CACHE) return null;
        return k.indexOf(PREFIX) === 0 ? caches['delete'](k) : null;
      }));
    }).then(function () { return self.clients.claim(); })
  );
});

self.addEventListener('message', function (event) {
  if (event.data === 'skipWaiting') self.skipWaiting();
});

self.addEventListener('fetch', function (event) {
  var req = event.request;
  if (req.method !== 'GET') return;

  var url = new URL(req.url);
  if (url.origin !== self.location.origin) return;

  /* A course's own worker owns these once it exists. Until then, the
     network answers or nothing does. */
  if (isCourse(url)) return;

  if (req.mode === 'navigate') {
    event.respondWith(
      fetch(req).then(function (res) {
        if (res && res.ok) {
          var copy = res.clone();
          caches.open(CACHE).then(function (c) { c.put(req, copy); });
        }
        return res;
      })['catch'](function () {
        return caches.match(req).then(function (hit) {
          return hit || caches.match('./');
        });
      })
    );
    return;
  }

  event.respondWith(
    caches.match(req).then(function (hit) {
      if (hit) return hit;
      return fetch(req).then(function (res) {
        if (res && res.status === 200 && res.type === 'basic') {
          var copy = res.clone();
          caches.open(CACHE).then(function (c) { c.put(req, copy); });
        }
        return res;
      });
    })
  );
});
